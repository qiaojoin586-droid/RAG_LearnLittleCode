"""Personal memory tables. Body is immutable except explicit history purge."""
import sqlalchemy as sa
from sqlalchemy.dialects import mysql
from app.models.base import Base
metadata=Base.metadata

user_memory_heads=sa.Table('user_memory_heads',metadata,
    sa.Column('last_source_request_id',sa.CHAR(32),nullable=True),
    sa.Column('last_source_message_id',sa.Integer(),nullable=True),
    sa.Column('last_source_completed_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),'mysql'),nullable=True),
    sa.Column('user_id',sa.String(36),nullable=False),
    sa.Column('active_revision_id',sa.String(36),nullable=True),
    sa.Column('last_revision_number',sa.BigInteger().with_variant(mysql.BIGINT(unsigned=True),"mysql"),nullable=False,server_default=sa.text('0')),
    sa.Column('head_version',sa.BigInteger().with_variant(mysql.BIGINT(unsigned=True),"mysql"),nullable=False,server_default=sa.text('0')),
    sa.Column('memory_epoch',sa.BigInteger().with_variant(mysql.BIGINT(unsigned=True),"mysql"),nullable=False,server_default=sa.text('0')),
    sa.Column('enabled',sa.Boolean(),nullable=False,server_default=sa.text('1')),
    sa.Column('auto_extract',sa.Boolean(),nullable=False,server_default=sa.text('1')),
    sa.Column('management_mode',sa.String(16),nullable=False,server_default=sa.text("'auto'")),
    sa.Column('created_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.Column('updated_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.CheckConstraint("management_mode IN ('auto','manual')"),
    sa.CheckConstraint('enabled IN (0,1) AND auto_extract IN (0,1)'),
    sa.PrimaryKeyConstraint('user_id'),
    sa.ForeignKeyConstraint(['user_id'],['users.uuid'],name='fk_um_head_owner'),
    mysql_engine="InnoDB",mysql_charset="utf8mb4",mysql_collate="utf8mb4_unicode_ci",
)

user_memory_revisions=sa.Table('user_memory_revisions',metadata,
    sa.Column('id',sa.String(36),nullable=False),
    sa.Column('user_id',sa.String(36),nullable=False),
    sa.Column('revision_number',sa.BigInteger().with_variant(mysql.BIGINT(unsigned=True),"mysql"),nullable=False),
    sa.Column('content_md',sa.Text().with_variant(mysql.MEDIUMTEXT(),"mysql"),nullable=False),
    sa.Column('content_hash',sa.CHAR(64).with_variant(mysql.CHAR(64,charset='ascii',collation='ascii_bin'),"mysql"),nullable=False),
    sa.Column('source_kind',sa.String(24),nullable=False),
    sa.Column('parent_revision_id',sa.String(36),nullable=True),
    sa.Column('source_request_id',sa.CHAR(32).with_variant(mysql.CHAR(32,charset='ascii',collation='ascii_bin'),"mysql"),nullable=True),
    sa.Column('created_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.CheckConstraint('revision_number > 0'),
    sa.CheckConstraint('OCTET_LENGTH(content_md) <= 32768').ddl_if(dialect="mysql"),
    sa.CheckConstraint("source_kind IN ('auto_init','model_generation','user_edit','proposal_accept','restore','clear')"),
    sa.PrimaryKeyConstraint('id'),
    sa.UniqueConstraint('user_id','id',name='uq_um_revision_owner'),
    sa.UniqueConstraint('user_id','revision_number',name='uq_um_revision_number'),
    sa.ForeignKeyConstraint(['user_id'],['user_memory_heads.user_id'],name='fk_um_revision_head'),
    sa.ForeignKeyConstraint(['user_id', 'parent_revision_id'],['user_memory_revisions.user_id', 'user_memory_revisions.id'],name='fk_um_revision_parent'),
    mysql_engine="InnoDB",mysql_charset="utf8mb4",mysql_collate="utf8mb4_unicode_ci",
)

user_memory_jobs=sa.Table('user_memory_jobs',metadata,
    sa.Column('id',sa.String(36),nullable=False),
    sa.Column('user_id',sa.String(36),nullable=False),
    sa.Column('source_request_id',sa.CHAR(32).with_variant(mysql.CHAR(32,charset='ascii',collation='ascii_bin'),"mysql"),nullable=False),
    sa.Column('source_message_id',sa.Integer().with_variant(mysql.INTEGER(unsigned=False),"mysql"),nullable=True),
    sa.Column('source_snapshot',sa.JSON(),nullable=True),
    sa.Column('base_revision_id',sa.String(36),nullable=True),
    sa.Column('expected_head_version',sa.BigInteger().with_variant(mysql.BIGINT(unsigned=True),"mysql"),nullable=False),
    sa.Column('memory_epoch',sa.BigInteger().with_variant(mysql.BIGINT(unsigned=True),"mysql"),nullable=False),
    sa.Column('scope_type',sa.String(16),nullable=False),
    sa.Column('scope_id',sa.String(64),nullable=False),
    sa.Column('config_release_id',sa.String(36),nullable=False),
    sa.Column('generation_number',sa.Integer().with_variant(mysql.INTEGER(unsigned=True),"mysql"),nullable=False,server_default=sa.text('1')),
    sa.Column('status',sa.String(24),nullable=False),
    sa.Column('attempt_count',sa.Integer().with_variant(mysql.INTEGER(unsigned=True),"mysql"),nullable=False,server_default=sa.text('0')),
    sa.Column('lease_owner',sa.String(36),nullable=True),
    sa.Column('lease_until',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=True),
    sa.Column('deadline_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.Column('proposal_expires_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=True),
    sa.Column('proposed_content_md',sa.Text().with_variant(mysql.MEDIUMTEXT(),"mysql"),nullable=True),
    sa.Column('proposed_content_hash',sa.CHAR(64).with_variant(mysql.CHAR(64,charset='ascii',collation='ascii_bin'),"mysql"),nullable=True),
    sa.Column('applied_revision_id',sa.String(36),nullable=True),
    sa.Column('error_reason',sa.String(64),nullable=True),
    sa.Column('created_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.Column('updated_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.CheckConstraint('attempt_count <= 2'),
    sa.CheckConstraint('generation_number > 0'),
    sa.CheckConstraint('OCTET_LENGTH(proposed_content_md) <= 32768').ddl_if(dialect="mysql"),
    sa.CheckConstraint("status IN ('queued','running','proposed','applied','no_change','failed','obsolete','cancelled','skipped_limit')"),
    sa.PrimaryKeyConstraint('id'),
    sa.UniqueConstraint('user_id','source_request_id',name='uq_um_job_source'),
    sa.UniqueConstraint('user_id','id',name='uq_um_job_owner'),
    sa.Index('ix_um_job_poll','status','lease_until','created_at'),
    sa.ForeignKeyConstraint(['user_id'],['user_memory_heads.user_id'],name='fk_um_job_head'),
    sa.ForeignKeyConstraint(['user_id', 'base_revision_id'],['user_memory_revisions.user_id', 'user_memory_revisions.id'],name='fk_um_job_base'),
    sa.ForeignKeyConstraint(['user_id', 'applied_revision_id'],['user_memory_revisions.user_id', 'user_memory_revisions.id'],name='fk_um_job_applied'),
    sa.ForeignKeyConstraint(['scope_type', 'scope_id', 'config_release_id'],['ai_config_releases.scope_type', 'ai_config_releases.scope_id', 'ai_config_releases.id'],name='fk_um_job_release'),
    mysql_engine="InnoDB",mysql_charset="utf8mb4",mysql_collate="utf8mb4_unicode_ci",
)

user_memory_requests=sa.Table('user_memory_requests',metadata,
    sa.Column('id',sa.String(36),nullable=False),
    sa.Column('user_id',sa.String(36),nullable=False),
    sa.Column('action',sa.String(24),nullable=False),
    sa.Column('request_key',sa.String(128).with_variant(mysql.VARCHAR(128,charset='utf8mb4',collation='utf8mb4_bin'),"mysql"),nullable=False),
    sa.Column('payload_hash',sa.CHAR(64).with_variant(mysql.CHAR(64,charset='ascii',collation='ascii_bin'),"mysql"),nullable=False),
    sa.Column('hash_key_version',sa.String(64),nullable=False),
    sa.Column('status',sa.String(16),nullable=False),
    sa.Column('result_metadata',sa.JSON(),nullable=True),
    sa.Column('created_at',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.Column('replay_until',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.Column('tombstone_until',sa.DateTime().with_variant(mysql.DATETIME(fsp=6),"mysql"),nullable=False),
    sa.CheckConstraint("action IN ('save','settings','restore','generate','apply','dismiss','clear')"),
    sa.CheckConstraint("status IN ('succeeded','failed','expired')"),
    sa.PrimaryKeyConstraint('id'),
    sa.UniqueConstraint('user_id','action','request_key',name='uq_um_request'),
    sa.ForeignKeyConstraint(['user_id'],['users.uuid'],name='fk_um_request_owner'),
    mysql_engine="InnoDB",mysql_charset="utf8mb4",mysql_collate="utf8mb4_unicode_ci",
)

user_memory_heads.append_constraint(sa.ForeignKeyConstraint(['user_id','active_revision_id'],['user_memory_revisions.user_id','user_memory_revisions.id'],name='fk_um_head_revision',use_alter=True))
MEMORY_TABLES=(user_memory_heads,user_memory_revisions,user_memory_jobs,user_memory_requests,)
